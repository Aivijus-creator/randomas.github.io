#!/usr/bin/env python3
"""Import character designs from the "Monstergarten – 3D veikėjai" HTML page into
src/shared/World/CharacterData.lua.

Usage:  python3 tools/import_characters.py path/to/Monstergarten_3D_veikejai.html

Each part in the HTML is [shape, position, size, colour, rotationDegXYZ, transparency, glow]
with shape s = sphere (ellipsoid), b = box, c = cylinder (axis along X). Units are multiplied by the
character's `scale` to get studs; `lift` (studs) raises floating characters.
"""
import json, re, sys, os

def lua(v):
    if isinstance(v, str):
        return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        r = round(float(v), 4)
        return str(int(r)) if r == int(r) else repr(r)
    if isinstance(v, list):
        return "{" + ", ".join(lua(x) for x in v) + "}"
    raise TypeError(v)

def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    m = re.search(r"const DATA=(\[.*?\]);\n", src, re.S)
    if not m:
        sys.exit("DATA block not found in the HTML file")
    data = json.loads(m.group(1))
    out = ["--!strict", "-- AUTO-GENERATED by tools/import_characters.py from the 3D character sheet. Do not edit by hand.",
           "-- Part = { shape, {x,y,z}, {sx,sy,sz}, colourHex, {rx,ry,rz} degrees, transparency, glow(0/1) }", "", "return {"]
    for folder in ("Babies", "Parents", "NPCs"):
        out.append(f"\t{folder} = {{")
        for d in data:
            if d["folder"] != folder:
                continue
            out.append(f"\t\t{d['name']} = {{")
            out.append(f"\t\t\tName = {lua(d.get('lt', d['name']))}, Scale = {lua(d['scale'])}, Lift = {lua(d.get('lift', 0))}, Height = {lua(d['h'])}, Width = {lua(d['w'])},")
            out.append("\t\t\tParts = {")
            for p in d["parts"]:
                out.append(f"\t\t\t\t{{ {lua(p[0])}, {lua(p[1])}, {lua(p[2])}, {lua(p[3])}, {lua(p[4])}, {lua(p[5])}, {lua(p[6])} }},")
            out.append("\t\t\t},")
            out.append("\t\t},")
        out.append("\t},")
    out.append("}")
    dst = os.path.join(os.path.dirname(__file__), "..", "src", "shared", "World", "CharacterData.lua")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"Wrote {len(data)} characters to {os.path.normpath(dst)}")

if __name__ == "__main__":
    main()
