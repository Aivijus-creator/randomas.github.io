return function(t)
	local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")
	local P = require(Shared.Logic.ProgressionMath)

	t.case("daycare levels", function()
		t.eq(P.daycareLevel(0), 1)
		t.eq(P.daycareLevel(4), 1)
		t.eq(P.daycareLevel(5), 2)
		t.eq(P.daycareLevel(30), 5)
		t.eq(P.daycareLevel(9999), 15)
	end)
	t.case("unlocks", function()
		t.ok(P.isUnlocked(0, "Baby:Dragling"))
		t.ok(not P.isUnlocked(0, "Baby:Vampy"))
		t.ok(P.isUnlocked(12, "Baby:Vampy"))
		t.ok(not P.isUnlocked(29, "Room:Basement"))
		t.ok(P.isUnlocked(30, "Room:Basement"))
		t.ok(P.isUnlocked(0, "Tool:Extinguisher"))
		t.ok(not P.isUnlocked(0, "Tool:Net"))
	end)
	t.case("xp", function()
		t.eq(P.xpForLevel(1), 100)
		local lvl, xp, gained = P.applyXP(1, 90, 20)
		t.eq(lvl, 2)
		t.eq(xp, 10)
		t.eq(#gained, 1)
	end)
	t.case("daily reward streak", function()
		local ok, streak, coins = P.dailyReward(10, 3, 11)
		t.ok(ok)
		t.eq(streak, 4)
		t.eq(coins, 150)
		ok = P.dailyReward(11, 4, 11)
		t.ok(not ok)
		ok, streak, coins = P.dailyReward(5, 6, 11)
		t.eq(streak, 1)
		t.eq(coins, 50)
		ok, streak, coins = P.dailyReward(10, 7, 11)
		t.eq(streak, 8)
		t.eq(coins, 50)
	end)
end
