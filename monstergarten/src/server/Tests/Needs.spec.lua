return function(t)
	local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")
	local NeedMath = require(Shared.Logic.NeedMath)

	t.case("player scale", function()
		t.eq(NeedMath.playerScale(1), 0.8)
		t.eq(NeedMath.playerScale(3), 1.0)
		t.eq(NeedMath.playerScale(6), 1.15)
		t.eq(NeedMath.playerScale(12), 1.15)
	end)
	t.case("decay", function()
		t.near(NeedMath.decayRate("Hunger", 2, 1.35, 3), 0.7 * 2 * 1.35, 1e-9)
		t.near(NeedMath.decayRate("Warmth", 1, 1, 1), 0.6 * 0.8, 1e-9)
		t.eq(NeedMath.decayRate("Nope", 1, 1, 1), 0)
	end)
	t.case("states", function()
		t.eq(NeedMath.state(0), "Tantrum")
		t.eq(NeedMath.state(10), "Crying")
		t.eq(NeedMath.state(30), "Bubble")
		t.eq(NeedMath.state(50), "Normal")
		t.eq(NeedMath.state(80), "Happy")
	end)
	t.case("mood", function()
		t.eq(NeedMath.mood({ Hunger = 50, Sleep = 100 }), 75)
	end)
end
