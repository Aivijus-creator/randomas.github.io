return function(t)
	local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")
	local Scoring = require(Shared.Logic.Scoring)

	t.case("perfect baby", function()
		t.eq(Scoring.babyScore({ TantrumSeconds = 0, InTantrumAtEnd = false, Escaped = false, GhostHidden = false, AllNeedsHappy = true }), 100)
	end)
	t.case("penalties stack and clamp", function()
		t.eq(Scoring.babyScore({ TantrumSeconds = 40, InTantrumAtEnd = true, Escaped = false, GhostHidden = false, AllNeedsHappy = false }), 70)
		t.eq(Scoring.babyScore({ TantrumSeconds = 400, InTantrumAtEnd = true, Escaped = true, GhostHidden = true, AllNeedsHappy = false }), 0)
	end)
	t.case("building", function()
		t.eq(Scoring.buildingScore({ AvgFurnitureHP = 90, Trash = 5, Spills = 2, FireBurning = true }), 71)
	end)
	t.case("final + stars", function()
		local f = Scoring.finalScore({ 100, 80 }, 70, 4)
		t.near(f, 0.7 * 90 + 0.3 * 70 + 4, 1e-9)
		t.eq(Scoring.stars(85), 3)
		t.eq(Scoring.stars(84.9), 2)
		t.eq(Scoring.stars(60), 2)
		t.eq(Scoring.stars(35), 1)
		t.eq(Scoring.stars(34), 0)
	end)
	t.case("event bonus capped at 10", function()
		t.near(Scoring.finalScore({ 50 }, 50, 50), 60, 1e-9)
	end)
	t.case("coins", function()
		t.eq(Scoring.coins(80, 2, 50, 1.5), math.floor((50 + 160 + 50 + 50) * 1.5 + 0.5))
	end)
	t.case("xp capped", function()
		t.eq(Scoring.xp(500, 20, 150), 150)
		t.eq(Scoring.xp(10, 20, 150), 30)
	end)
end
