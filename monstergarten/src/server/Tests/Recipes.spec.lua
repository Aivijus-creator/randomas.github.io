return function(t)
	local Shared = game:GetService("ReplicatedStorage"):WaitForChild("Shared")
	local RecipeMatch = require(Shared.Logic.RecipeMatch)
	local Babies = require(Shared.Config.Babies)

	t.case("exact match any order", function()
		t.eq(RecipeMatch.find("Oven", { "Pepper", "Meat" }).Dish, "SpicySteak")
		t.eq(RecipeMatch.find("Pot", { "Milk", "Fish" }).Dish, "FishMash")
		t.eq(RecipeMatch.find("Blender", { "Beet" }).Dish, "BeetJuice")
		t.ok(RecipeMatch.find("Pot", { "Meat", "Pepper" }) == nil)
	end)
	t.case("cake only during event", function()
		t.ok(RecipeMatch.find("Oven", { "Flour", "Milk", "Berries" }) == nil)
		t.eq(RecipeMatch.find("Oven", { "Flour", "Milk", "Berries" }, true).Dish, "Cake")
	end)
	t.case("canAdd prefixes", function()
		t.ok(RecipeMatch.canAdd("Oven", {}, "Meat"))
		t.ok(RecipeMatch.canAdd("Oven", { "Meat" }, "Pepper"))
		t.ok(not RecipeMatch.canAdd("Oven", { "Meat" }, "Fish"))
		t.ok(not RecipeMatch.canAdd("Oven", { "Flour", "Milk" }, "Berries"))
		t.ok(RecipeMatch.canAdd("Oven", { "Flour", "Milk" }, "Berries", true))
		t.ok(not RecipeMatch.canAdd("Freezer", {}, "Meat"))
	end)
	t.case("feeding", function()
		local D = Babies.Defs
		t.eq(RecipeMatch.feedResult(D.Dragling, "Dish", "SpicySteak"), "Favorite")
		t.eq(RecipeMatch.feedResult(D.Dragling, "Dish", "Porridge"), "Suitable")
		t.eq(RecipeMatch.feedResult(D.Dragling, "Dish", "FishMash"), "Wrong")
		t.eq(RecipeMatch.feedResult(D.Dragling, "Ingredient", "Meat"), "Wrong")
		t.eq(RecipeMatch.feedResult(D.Slimy, "Ingredient", "Meat"), "Raw")
		t.eq(RecipeMatch.feedResult(D.Slimy, "Dish", "FishMash"), "Favorite")
		t.eq(RecipeMatch.feedResult(D.Ghostie, "Dish", "Porridge"), "NoEat")
		t.eq(RecipeMatch.feedResult(D.Yeti, "Ingredient", "Ice"), "Ice")
		t.eq(RecipeMatch.feedResult(D.Vampy, "Dish", "Cake"), "Cake")
	end)
end
