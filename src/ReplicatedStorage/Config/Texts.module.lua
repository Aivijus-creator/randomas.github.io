-- Grąžina tekstą pagal kalbą ir raktą; {vardai} pakeičiami args reikšmėmis.
function Texts.Get(lang, key, args)
	local dict = Texts[lang] or Texts.en
	local text = dict[key]
	if text == nil then
		text = Texts.en[key]
	end
	if text == nil then
		return tostring(key)
	end
	if type(text) ~= "string" then
		return text
	end
	if args then
		text = string.gsub(text, "{(%w+)}", function(name)
			local value = args[name]
			if value == nil then
				return "{" .. name .. "}"
			end
			return tostring(value)
		end)
	end
	return text
end

return Texts
